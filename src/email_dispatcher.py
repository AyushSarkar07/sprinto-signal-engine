"""Step 7 — Test-only email dispatch (Gmail API with OAuth, or SMTP with an app password).

SAFETY MODEL — this is an academic demonstration:
  * DRY_RUN=true by default: messages are written to output/generated_emails/*.eml, nothing is sent.
  * Sending requires BOTH DRY_RUN=false AND the explicit --send-test flag.
  * The only deliverable recipient is TEST_TO_EMAIL. `assert_allowed_recipient` rejects anything else
    (other addresses, lists, display-name tricks, header injection), and the fully built MIME message is
    re-checked immediately before every send (To/Cc/Bcc), so no code path can reach a prospect.
"""

from __future__ import annotations

import base64
import logging
import re
import smtplib
from email.message import EmailMessage
from email.utils import getaddresses, parseaddr
from pathlib import Path
from typing import Optional

from src.models import DispatchResult, GeneratedEmail

log = logging.getLogger(__name__)
GMAIL_SCOPES = ["https://www.googleapis.com/auth/gmail.send"]
EMAIL_RX = re.compile(r"^[A-Za-z0-9._%+\-]+@[A-Za-z0-9.\-]+\.[A-Za-z]{2,}$")


class RecipientNotAllowed(PermissionError):
    pass


def assert_allowed_recipient(recipient: str, test_to_email: str) -> str:
    """Return the normalised address if and only if it is exactly TEST_TO_EMAIL; otherwise raise."""
    if not test_to_email or not EMAIL_RX.match(test_to_email.strip()):
        raise RecipientNotAllowed("TEST_TO_EMAIL is not configured with a valid address; refusing to send anything.")
    if not isinstance(recipient, str) or any(ch in recipient for ch in "\r\n,;"):
        raise RecipientNotAllowed("Recipient contains list separators or line breaks; refusing.")
    name, addr = parseaddr(recipient)
    addr = addr.strip().lower()
    if "@" in name:
        raise RecipientNotAllowed("Display name contains an address; refusing.")
    if not addr or not EMAIL_RX.match(addr) or addr != recipient.strip().lower().split("<")[-1].rstrip(">").strip():
        raise RecipientNotAllowed(f"Recipient '{recipient}' is not a single plain address; refusing.")
    if addr != test_to_email.strip().lower():
        raise RecipientNotAllowed(f"Recipient '{addr}' is not the configured TEST_TO_EMAIL; refusing.")
    return addr


def assert_message_safe(msg: EmailMessage, test_to_email: str) -> None:
    """Final gate on the built MIME message: exactly one recipient, and it is TEST_TO_EMAIL."""
    for hdr in ("Cc", "Bcc", "Resent-To", "Resent-Cc", "Resent-Bcc"):
        if msg.get_all(hdr):
            raise RecipientNotAllowed(f"Message carries a {hdr} header; refusing.")
    tos = getaddresses(msg.get_all("To", []))
    if len(tos) != 1:
        raise RecipientNotAllowed(f"Message must have exactly one recipient, found {len(tos)}.")
    assert_allowed_recipient(tos[0][1], test_to_email)


def render_preview(email: GeneratedEmail, company: str, contact_name: str, prospect_email: Optional[str],
                   qualification_reasoning: list[str], contact_reasoning: str, pain_reasoning: str) -> str:
    sep = "-" * 32
    return "\n".join([
        "TEST PREVIEW",
        f"Intended recipient: {contact_name}",
        f"Company: {company}",
        f"Original prospect email: {prospect_email or 'not available (no verified address — would need Hunter/Apollo verification)'}",
        "", sep, "",
        f"Subject: {email.subject}", "",
        email.email_body, "", sep, "",
        "WHY THIS EMAIL WAS GENERATED", "",
        "Company qualification:", *[f"  - {r}" for r in qualification_reasoning[:4]], "",
        f"Why this individual: {contact_reasoning}", "",
        f"Hook observation: {email.personalisation_hook}", f"  Source: {email.hook_source_url}", "",
        f"Main pain point: {email.pain_point_used}", f"  Reasoning: {pain_reasoning}", "",
        f"Generated by: {'Claude' if email.provenance == 'claude' else 'deterministic fallback (Claude not used)'}",
        "Controlled test: this message can only ever be delivered to the TEST_TO_EMAIL inbox. The prospect was NOT contacted.",
    ])


def build_message(preview_text: str, subject: str, company: str, test_to_email: str, sender: str) -> EmailMessage:
    to = assert_allowed_recipient(test_to_email, test_to_email)
    msg = EmailMessage()
    msg["To"] = to
    msg["From"] = sender or to
    msg["Subject"] = f"[TEST PREVIEW] {company}: {subject}"
    msg["X-Sprinto-Signal-Engine"] = "test-preview"
    msg.set_content(preview_text)
    return msg


class Dispatcher:
    def __init__(self, settings, send_enabled: bool = False):
        self.s = settings
        self.send_enabled = send_enabled and not settings.dry_run
        self.out_dir = settings.output_dir / "generated_emails"
        self.out_dir.mkdir(parents=True, exist_ok=True)
        self._gmail = None

    def credentials_problem(self) -> Optional[str]:
        if self.s.email_backend == "smtp":
            if not (self.s.smtp_user and self.s.smtp_app_password):
                return "SMTP_USER / SMTP_APP_PASSWORD not set (create a Google app password: myaccount.google.com/apppasswords)."
            return None
        if self.s.gmail_token_path.exists():
            return None
        if not (self.s.gmail_client_id and self.s.gmail_client_secret):
            return ("Gmail OAuth not configured: set GMAIL_CLIENT_ID and GMAIL_CLIENT_SECRET (Google Cloud Console → "
                    "APIs & Services → Credentials → OAuth client ID → Desktop app), then run `python main.py --gmail-auth`.")
        return "Gmail token missing: run `python main.py --gmail-auth` once to authorise in the browser."

    def dispatch(self, email: GeneratedEmail, slug: str, preview_text: str, company: str) -> DispatchResult:
        try:
            msg = build_message(preview_text, email.subject, company, self.s.test_to_email, self.s.smtp_user or self.s.test_to_email)
        except RecipientNotAllowed as exc:
            # Still save a preview so the run is demonstrable, but nothing can be sent.
            path = self.out_dir / f"{slug}.txt"
            path.write_text(preview_text, encoding="utf-8")
            return DispatchResult(status="blocked_by_guard", preview_path=str(path), detail=str(exc))
        path = self.out_dir / f"{slug}.eml"
        path.write_bytes(bytes(msg))
        if not self.send_enabled:
            why = "DRY_RUN=true" if self.s.dry_run else "--send-test flag not given"
            return DispatchResult(status="dry_run_preview", preview_path=str(path), detail=f"Not sent ({why}). Preview saved.")
        problem = self.credentials_problem()
        if problem:
            return DispatchResult(status="blocked_missing_credentials", preview_path=str(path), detail=problem)
        try:
            assert_message_safe(msg, self.s.test_to_email)
            if self.s.email_backend == "smtp":
                mid = self._send_smtp(msg)
            else:
                mid = self._send_gmail(msg)
            return DispatchResult(status="sent", delivered_to=msg["To"], preview_path=str(path), message_id=mid,
                                  detail=f"Delivered via {self.s.email_backend}")
        except RecipientNotAllowed as exc:
            return DispatchResult(status="blocked_by_guard", preview_path=str(path), detail=str(exc))
        except Exception as exc:
            log.error("Send failed: %s", exc.__class__.__name__)
            return DispatchResult(status="error", preview_path=str(path), detail=f"Send failed: {exc.__class__.__name__}")

    # ---- backends
    def _send_smtp(self, msg: EmailMessage) -> str:
        assert_message_safe(msg, self.s.test_to_email)
        with smtplib.SMTP(self.s.smtp_host, self.s.smtp_port, timeout=30) as smtp:
            smtp.starttls()
            smtp.login(self.s.smtp_user, self.s.smtp_app_password)
            smtp.send_message(msg, to_addrs=[assert_allowed_recipient(msg["To"], self.s.test_to_email)])
        return "smtp"

    def _gmail_service(self):
        if self._gmail is None:
            from google.oauth2.credentials import Credentials
            from google.auth.transport.requests import Request
            from googleapiclient.discovery import build
            creds = Credentials.from_authorized_user_file(str(self.s.gmail_token_path), GMAIL_SCOPES)
            if not creds.valid and creds.expired and creds.refresh_token:
                creds.refresh(Request())
                self.s.gmail_token_path.write_text(creds.to_json())
            self._gmail = build("gmail", "v1", credentials=creds, cache_discovery=False)
        return self._gmail

    def _send_gmail(self, msg: EmailMessage) -> str:
        assert_message_safe(msg, self.s.test_to_email)
        raw = base64.urlsafe_b64encode(bytes(msg)).decode()
        res = self._gmail_service().users().messages().send(userId="me", body={"raw": raw}).execute()
        return res.get("id", "")


def gmail_authorize(settings) -> Path:
    """One-time interactive OAuth consent (opens a browser). Stores the token at GMAIL_TOKEN_PATH."""
    from google_auth_oauthlib.flow import InstalledAppFlow
    if not (settings.gmail_client_id and settings.gmail_client_secret):
        raise SystemExit("Set GMAIL_CLIENT_ID and GMAIL_CLIENT_SECRET in .env first.")
    config = {"installed": {"client_id": settings.gmail_client_id, "client_secret": settings.gmail_client_secret,
                            "auth_uri": "https://accounts.google.com/o/oauth2/auth",
                            "token_uri": "https://oauth2.googleapis.com/token",
                            "redirect_uris": ["http://localhost"]}}
    flow = InstalledAppFlow.from_client_config(config, GMAIL_SCOPES)
    creds = flow.run_local_server(port=0)
    settings.gmail_token_path.parent.mkdir(parents=True, exist_ok=True)
    settings.gmail_token_path.write_text(creds.to_json())
    return settings.gmail_token_path
